const fs = require('fs');
const vm = require('vm');
const path = process.argv[2];
const html = fs.readFileSync(path, 'utf8');
const start = html.indexOf('<script>const TH=');
const end = html.indexOf('</script>', start);
let code = html.slice(start + 8, end).replace(/boot\(\);\s*$/, '');
code += '\n;globalThis.__out={RES,DEC,NOTES,SIMPLE,TH,TERMS};';
const sandbox = { console };
vm.createContext(sandbox);
vm.runInContext(code, sandbox, { timeout: 20000 });
const { RES, DEC, NOTES, SIMPLE, TH, TERMS } = sandbox.__out;
console.log('sets', JSON.stringify(RES.sets).slice(0, 1200));
console.log('actors', JSON.stringify(RES.actors).slice(0, 600));
console.log('column sample', JSON.stringify(Object.entries(RES.columns).slice(0, 2)));
console.log('view?', Object.keys(RES.tables).filter(t => t.startsWith('v_')).slice(0, 5));
console.log('DEC', JSON.stringify(DEC).slice(0, 1200));
fs.writeFileSync('_work/scripts/v15_consts_dump.json', JSON.stringify({ RES, DEC, NOTES, SIMPLE, TH, TERMS }, null, 1));
console.log('wrote dump');
