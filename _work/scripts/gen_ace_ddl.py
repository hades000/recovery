# -*- coding: utf-8 -*-
"""Turn the ACE workbook into runnable PostgreSQL DDL plus a flat column extract."""
import csv
import io
import re
import openpyxl

SRC = r'ACE schema\ACE-data-schema_20261104.xlsx'
OUT_SQL = r'15 ACE DB Alignment\ACE Schema PostgreSQL v1.sql'
OUT_CSV = r'15 ACE DB Alignment\ACE Schema Extract v1.csv'

wb = openpyxl.load_workbook(SRC, data_only=True)
ov = wb['Overview']
tables = []
for r in ov.iter_rows(min_row=10, values_only=True):
    if r[1] and r[0] and str(r[0]) != 'Worksheet':
        tables.append((r[0], r[1], r[2]))

TYPE_MAP = [
    (r'^BINARY VARYING\((\d+)\)$', lambda m: 'bytea'),
    (r'^CHARACTER VARYING\((\d+)\)$', lambda m: 'varchar(%s)' % m.group(1) if int(m.group(1)) < 100000 else 'text'),
    (r'^CHARACTER\((\d+)\)$', lambda m: 'char(%s)' % m.group(1)),
    (r'^CHARACTER VARYING$', lambda m: 'varchar'),
    (r'^NUMERIC\((\d+),(\d+)\)$', lambda m: 'numeric(%s,%s)' % (m.group(1), m.group(2))),
    (r'^DECIMAL\((\d+),(\d+)\)$', lambda m: 'numeric(%s,%s)' % (m.group(1), m.group(2))),
    (r'^TIMESTAMP WITH TIME ZONE \[fractional precision (\d+)\]$', lambda m: 'timestamptz(%s)' % m.group(1)),
    (r'^TIMESTAMP \[fractional precision (\d+)\]$', lambda m: 'timestamp(%s)' % m.group(1)),
    (r'^TIMESTAMP WITH TIME ZONE$', lambda m: 'timestamptz'),
    (r'^TIMESTAMP$', lambda m: 'timestamp'),
    (r'^BIGINT$', lambda m: 'bigint'),
    (r'^INTEGER$', lambda m: 'integer'),
    (r'^SMALLINT$', lambda m: 'smallint'),
    (r'^BOOLEAN$', lambda m: 'boolean'),
    (r'^DATE$', lambda m: 'date'),
    (r'^DOUBLE PRECISION$', lambda m: 'double precision'),
    (r'^REAL$', lambda m: 'real'),
]


def pgtype(t):
    t = (t or '').strip()
    for pat, fn in TYPE_MAP:
        m = re.match(pat, t)
        if m:
            return fn(m)
    return t.lower()


def pgdefault(d):
    d = (d or '').strip()
    if not d:
        return None
    if d.startswith('GENERATED BY DEFAULT AS IDENTITY'):
        return 'generated by default as identity'
    if d.upper() == 'CURRENT_TIMESTAMP':
        return 'default current_timestamp'
    if d.upper() == 'LOCALTIMESTAMP':
        return 'default localtimestamp'
    if d.upper() == 'FALSE':
        return 'default false'
    if d.upper() == 'TRUE':
        return 'default true'
    if d == "''":
        return "default ''"
    if d.upper() == 'NULL':
        return None
    return 'default %s' % d


extract = []
pk = {}
fks = []
uniques = []
indexes = []
checks = []
coldefs_all = {}

for sheet, table, category in tables:
    ws = wb[sheet]
    coldefs = []
    mode = None
    for r in ws.iter_rows(values_only=True):
        if not r or r[0] is None:
            continue
        first = str(r[0]).strip()
        if first == '#':
            mode = 'cols'
            continue
        if first == 'Constraint name':
            mode = 'cons'
            continue
        if first.startswith('Explicit index name'):
            mode = 'idx'
            continue
        if first.startswith('Physical table') or first.startswith('Back to Overview'):
            continue
        if mode == 'cols':
            if not re.match(r'^\d+$', first):
                continue
            name, typ, nullable, pkflag, uq, dflt, fk = r[1], r[2], r[3], r[4], r[5], r[6], r[7]
            coldefs.append((name, typ, nullable, pkflag, uq, dflt))
            extract.append([category, table, name, pgtype(typ), nullable, 'YES' if pkflag else '',
                            uq or '', fk or ''])
        elif mode == 'cons':
            cells = list(r[:7])
            if not cells[1]:
                continue
            ctype = str(cells[1]).strip()
            cols = [c.strip() for c in str(cells[2] or '').split(',') if c.strip()]
            if ctype == 'FOREIGN KEY':
                ref = str(cells[3] or '').strip()
                m = re.match(r'^([a-z0-9_]+)\s*\((.*)\)$', ref)
                if m:
                    reftable = m.group(1)
                    refcols = [c.strip() for c in m.group(2).split(',') if c.strip()]
                    if len(refcols) == len(cols):
                        fks.append((table, first, cols, reftable, refcols, str(cells[5] or 'NO ACTION'), str(cells[6] or 'NO ACTION')))
            elif ctype == 'PRIMARY KEY':
                pk[table] = cols
            elif ctype == 'UNIQUE':
                uniques.append((first, table, cols))
            elif ctype == 'CHECK':
                expr = str(cells[6] or '').strip()
                if expr:
                    checks.append((first, table, expr))
        elif mode == 'idx':
            if first.startswith('No explicit'):
                continue
            cols_idx = str(r[2] or '')
            parsed = [c.strip().split()[0] for c in cols_idx.split(',') if c.strip()]
            if parsed:
                indexes.append((first, table, parsed, str(r[1]).strip().upper() == 'TRUE'))
    coldefs_all[table] = coldefs

lines = []
lines.append('-- ACE database schema, PostgreSQL')
lines.append('-- Generated from ACE schema/ACE-data-schema_20261104.xlsx (ACE backend, commit 96b0d1c6, generated 2026-11-04).')
lines.append('-- 62 tables, 547 columns, 121 foreign keys. Schema only: no data rows.')
lines.append('-- Used to compile the Recovery Workbench ACE source views. Do not edit by hand: the ACE team owns this schema.')
lines.append('')
lines.append('CREATE SCHEMA IF NOT EXISTS public;')
lines.append('')

for sheet, table, category in tables:
    coldefs = coldefs_all[table]
    parts = []
    for name, typ, nullable, pkflag, uq, dflt in coldefs:
        piece = '    %s %s' % (name, pgtype(typ))
        d = pgdefault(dflt)
        if d:
            piece += ' ' + d
        if str(nullable).strip().upper() == 'NO' and not d:
            piece += ' not null'
        parts.append(piece)
    lines.append('-- %s (%s)' % (table, category))
    lines.append('CREATE TABLE public.%s (' % table)
    lines.append(',\n'.join(parts))
    lines.append(');')
    lines.append('')

for table, cols in pk.items():
    lines.append('ALTER TABLE public.%s ADD CONSTRAINT pk_%s PRIMARY KEY (%s);' % (table, table, ', '.join(cols)))
lines.append('')
for name, table, cols in uniques:
    lines.append('ALTER TABLE public.%s ADD CONSTRAINT %s UNIQUE (%s);' % (table, name, ', '.join(cols)))
lines.append('')
for table, name, cols, reftable, refcols, onupd, ondel in fks:
    lines.append('ALTER TABLE public.%s ADD CONSTRAINT %s FOREIGN KEY (%s) REFERENCES public.%s (%s) ON UPDATE %s ON DELETE %s;'
                 % (table, name, ', '.join(cols), reftable, ', '.join(refcols), onupd, ondel))
lines.append('')
for name, table, cols, uniq in indexes:
    lines.append('CREATE %sINDEX %s ON public.%s (%s);' % ('UNIQUE ' if uniq else '', name, table, ', '.join(cols)))
lines.append('')

io.open(OUT_SQL, 'w', encoding='utf-8').write('\n'.join(lines))

with io.open(OUT_CSV, 'w', encoding='utf-8', newline='') as f:
    w = csv.writer(f)
    w.writerow(['category', 'table', 'column', 'sql_type', 'nullable', 'primary_key', 'unique_keys', 'foreign_key'])
    w.writerows(extract)

print('tables', len(tables), 'columns', len(extract), 'fks', len(fks), 'pk', len(pk), 'uq', len(uniques), 'idx', len(indexes), 'checks', len(checks))
print('wrote', OUT_SQL, OUT_CSV)
